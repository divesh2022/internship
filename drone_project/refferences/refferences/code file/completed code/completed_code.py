        optimal_params_found_drone['Kp_x'], optimal_params_found_drone['Ki_x'], optimal_params_found_drone['Kd_x'],
        optimal_params_found_drone['Kp_y'], optimal_params_found_drone['Ki_y'], optimal_params_found_drone['Kd_y'],
