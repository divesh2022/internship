def create_boat(x, y, theta, scale=0.8):

    # Triangle boat shape
    boat = np.array(
        [
            [1.5, 0],
            [-1, 0.7],
            [-0.5, 0],
            [-1, -0.7]
        ]
    ) * scale

    # Rotation matrix
    R = np.array(
        [
            [np.cos(theta), -np.sin(theta)],
            [np.sin(theta), np.cos(theta)]
        ]
    )

    rotated_boat = boat @ R.T

    rotated_boat[:, 0] += x
    rotated_boat[:, 1] += y

    return rotated_boat


